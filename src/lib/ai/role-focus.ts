export function formatReviewLevelGuidance(level: ReviewLevel): string {
  const common = `審査レベル: ${level}（${REVIEW_LEVEL_LABELS[level]}）`;
  if (level === "experiment") {
    return [
      common,
      "成熟度: アイデア・小規模実験。企画者を追い詰めるな。育てる。",
      "禁止: 具体的ROI・利益率・回収期間・詳細数値の要求。",
      "議論せよ: 仮説は成立するか / 価値はあるか / 差別化できるか / 方向性は良いか。",
      "数字が出ても『現時点では不要』『将来検証しましょう』『PARKEDでよい』を優先。",
      "数値不足を責めず、構造確認・仮説検証へ進める。",
      "安全性・現場負荷・最小の試し方を見る。",
    ].join("\n");
  }
  if (level === "strategic") {
    return [
      common,
      "成熟度: 稟議・戦略投資。ここで初めてROI・利益率・回収・キャッシュ・撤退条件などの具体数字を要求してよい。",
      "技術負債・長期事業性も確認。ただし育てる姿勢は維持。",
    ].join("\n");
  }
  return [
    common,
    "成熟度: 標準。方向性・顧客価値・粗い費用感・実行体制・KPIの骨格まで。",
    "厳密な回収期間・詳細ROIは必須ではない。必要なら将来検証でよい。",
  ].join("\n");
}
